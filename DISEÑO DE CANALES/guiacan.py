    print(" - Angulo talud: theta = atan(1/m)")
    print(" - K = sqrt(1 - sin^2(theta)/sin^2(phi))")
    print(" - tau_p(lados) = K * tau_p")
    print("")
    print("Paso 3: Despejar tirante y:")
    print(" - Max cortante en lados = 0.76*g*y*S0")
